using Content.Client.UserInterface.Controls;
using Content.Shared._WW.Species;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WW.Species;

/// <summary>
/// WW: the Protectron module picker. Same layout as the cyborg chassis picker
/// (<see cref="Content.Client.Silicons.Borgs.BorgSelectTypeMenu"/>): modules on the left, the picked one's model
/// and description on the right, and a confirm button (click twice) because the choice is permanent.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ProtectronModuleMenu : FancyWindow
{
    private int? _selected;

    public event Action<int>? Confirmed;

    public ProtectronModuleMenu()
    {
        RobustXamlLoader.Load(this);
        ConfirmButton.OnPressed += _ =>
        {
            if (_selected is { } index)
                Confirmed?.Invoke(index);
        };
    }

    public void Populate(IReadOnlyList<ProtectronModuleOption> modules)
    {
        SelectionsContainer.RemoveAllChildren();
        var group = new ButtonGroup();
        for (var i = 0; i < modules.Count; i++)
        {
            var index = i;
            var module = modules[i];
            var button = new Button
            {
                Text = Loc.GetString(module.Name),
                Group = group,
            };
            button.OnPressed += _ => Show(index, module);
            SelectionsContainer.AddChild(button);
        }
    }

    private void Show(int index, ProtectronModuleOption module)
    {
        _selected = index;
        InfoContents.Visible = true;
        InfoPlaceholder.Visible = false;
        ConfirmButton.Disabled = false;

        NameLabel.Text = Loc.GetString(module.Name);
        DescriptionLabel.Text = Loc.GetString(module.Description);
        ChassisView.SetPrototype(module.Dummy);
    }
}
